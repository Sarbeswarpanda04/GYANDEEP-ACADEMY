const originalTextNodes = new WeakMap();
const normalizeText = (value) => value.trim().replace(/\s+/g, " ");
const odiaPhrases = Object.keys(odiaText)
  .filter((phrase) => phrase.length > 3)
  .sort((left, right) => right.length - left.length);

function translateTextNode(node, language) {
  if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
  const original = originalTextNodes.get(node);
  const normalized = normalizeText(original);
  if (!normalized) return;
  if (language === "or" && odiaText[normalized]) {
    const leading = original.match(/^\s*/)?.[0] ?? "";
    const trailing = original.match(/\s*$/)?.[0] ?? "";
    node.nodeValue = `${leading}${odiaText[normalized]}${trailing}`;
  } else if (language === "or") {
    const leading = original.match(/^\s*/)?.[0] ?? "";
    const trailing = original.match(/\s*$/)?.[0] ?? "";
    const core = normalized;
    const translated = odiaPhrases.reduce(
      (text, phrase) => text.replaceAll(phrase, odiaText[phrase]),
      core,
    );
    node.nodeValue = `${leading}${translated}${trailing}`;
  } else if (language === "en") {
    node.nodeValue = original;
  }
}

